export function generatePromptForUser(inputText: string = ''): string {
  if (!inputText.trim()) {
    return `${KANBUN_SYSTEM_PROMPT}\n【変換対象の漢文テキスト・問題文】\n(ここに大学入試問題や漢文本文を貼り付けてAIに送信してください)`;
  }
  return `${KANBUN_SYSTEM_PROMPT}\n【変換対象の漢文テキスト・問題文】\n${inputText}`;
}
